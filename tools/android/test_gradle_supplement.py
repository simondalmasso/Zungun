#!/usr/bin/env python3
"""Regression tests for semantic application of ORDER-080 checksum supplement."""
from __future__ import annotations
import importlib.util
import tempfile
import unittest
from pathlib import Path
import xml.etree.ElementTree as ET

_spec = importlib.util.spec_from_file_location(
    "verify_gradle_supplement",
    Path(__file__).with_name("verify-gradle-supplement.py"),
)
if _spec is None or _spec.loader is None:
    raise RuntimeError("GRADLE_SUPPLEMENT_HELPER_IMPORT_FAILED")
_helper = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_helper)

NS = "https://schema.gradle.org/dependency-verification"
def q(name: str) -> str:
    return f"{{{NS}}}{name}"

SAMPLE_PATCH = """diff --git a/android/gradle/verification-metadata.xml b/android/gradle/verification-metadata.xml
index 1234567..abcdef0 100644
--- a/android/gradle/verification-metadata.xml
+++ b/android/gradle/verification-metadata.xml
@@ -1,3 +1,7 @@
 <verification-metadata xmlns="https://schema.gradle.org/dependency-verification">
   <components>
+      <component group="org.example" name="example-bom" version="1.2">
+         <artifact name="example-bom-1.2.pom">
+            <sha256 value="0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef" origin="Generated by Gradle"/>
+         </artifact>
+      </component>
     </components>
 </verification-metadata>
"""

class GradleSupplementTests(unittest.TestCase):
    def metadata(self, path: Path) -> None:
        path.write_text(
            '<?xml version="1.0"?><verification-metadata xmlns="https://schema.gradle.org/dependency-verification"><components></components></verification-metadata>',
            encoding="utf-8",
        )

    def test_parses_exact_added_gav_artifact_hash(self):
        self.assertEqual(
            _helper.parse_supplement(SAMPLE_PATCH),
            {("org.example", "example-bom", "1.2", "example-bom-1.2.pom",
              "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef")},
        )

    def test_applies_supplement_idempotently(self):
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            metadata, patch = root / "metadata.xml", root / "supplement.patch"
            self.metadata(metadata)
            patch.write_text(SAMPLE_PATCH, encoding="utf-8")
            self.assertEqual(_helper.apply_supplement(metadata, patch), 1)
            _helper.verify_supplement_present(metadata, patch)
            self.assertEqual(_helper.apply_supplement(metadata, patch), 0)
            tree = ET.parse(metadata).getroot()
            self.assertEqual(len(tree.findall(f".//{q('sha256')}")), 1)

    def test_check_fails_when_exact_hash_is_missing(self):
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            metadata, patch = root / "metadata.xml", root / "supplement.patch"
            self.metadata(metadata)
            patch.write_text(SAMPLE_PATCH, encoding="utf-8")
            with self.assertRaisesRegex(SystemExit, "SUPPLEMENT_ENTRIES_MISSING"):
                _helper.verify_supplement_present(metadata, patch)

    def test_patch_context_without_exact_gav_artifact_fails_closed(self):
        with self.assertRaisesRegex(ValueError, "SUPPLEMENT_SHA256_WITHOUT_GAV_ARTIFACT_CONTEXT"):
            _helper.parse_supplement(
                "--- a/file\n+++ b/file\n@@ -1 +1 @@\n+<sha256 value=\"0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef\"/>\n"
            )

if __name__ == "__main__":
    unittest.main(verbosity=2)
