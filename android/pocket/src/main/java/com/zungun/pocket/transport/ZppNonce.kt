package com.zungun.pocket.transport

/**
 * Canonical ZPP/1 nonce byte layout. This is only a byte-encoding primitive;
 * it does not implement key derivation, encryption, peer authentication, or replay protection.
 *
 * Stable pair roles are established during authenticated pairing: A and B never
 * change roles during a rekey. A_TO_B and B_TO_A are distinct byte values.
 */
internal enum class ZppDirection(val wireCode: Int) {
    A_TO_B(0x00),
    B_TO_A(0x01)
}

internal object ZppNonce {
    const val SIZE_BYTES = 24
    const val MAX_EPOCH = 0xFFFF
    const val MAX_MESSAGE_ID = 0xFFFD

    /**
     * nonce24 = U16BE(epoch) || U16BE(messageId) || direction || 19 * 0x00
     *
     * The zero padding is deliberately generated by ByteArray initialization.
     * Never shorten or extend this nonce at a call site.
     */
    fun encode(epoch: Int, messageId: Int, direction: ZppDirection): ByteArray {
        require(epoch in 0..MAX_EPOCH) { "epoch must fit an unsigned 16-bit field" }
        require(messageId in 0..MAX_MESSAGE_ID) { "message ID is exhausted or reserved" }

        return ByteArray(SIZE_BYTES).also { nonce ->
            nonce[0] = (epoch ushr 8).toByte()
            nonce[1] = epoch.toByte()
            nonce[2] = (messageId ushr 8).toByte()
            nonce[3] = messageId.toByte()
            nonce[4] = direction.wireCode.toByte()
        }
    }
}
